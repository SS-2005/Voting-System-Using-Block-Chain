const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  console.log("--------------------------------------------------");
  console.log("Deploying Voting contract with account:", deployer.address);
  console.log("Account balance:", (await hre.ethers.provider.getBalance(deployer.address)).toString());
  console.log("--------------------------------------------------");

  const Voting = await hre.ethers.getContractFactory("Voting");
  const voting = await Voting.deploy();
  await voting.waitForDeployment();

  const contractAddress = await voting.getAddress();
  console.log(">>> Voting contract successfully deployed to:", contractAddress);
  console.log(">>> Administrator address set to:", deployer.address);
  console.log("--------------------------------------------------");

  // Ensure frontend folder exists
  const frontendDir = path.join(__dirname, "..", "frontend");
  if (!fs.existsSync(frontendDir)) {
    fs.mkdirSync(frontendDir, { recursive: true });
  }

  // Get contract artifact for ABI
  const artifactPath = path.join(__dirname, "..", "artifacts", "contracts", "Voting.sol", "Voting.json");
  let abi = [];
  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
    abi = artifact.abi;
  }

  // Write contract-data.js (works with both file:// and http://)
  const jsContent = `// Auto-generated by scripts/deploy.js
// Do not edit manually unless you are redeploying to a new address.
window.CONTRACT_ADDRESS = "${contractAddress}";
window.CONTRACT_ABI = ${JSON.stringify(abi, null, 2)};
`;
  fs.writeFileSync(path.join(frontendDir, "contract-data.js"), jsContent, "utf8");

  // Also write contract-info.json for reference
  const jsonContent = JSON.stringify({
    address: contractAddress,
    admin: deployer.address,
    network: hre.network.name,
    abi: abi
  }, null, 2);
  fs.writeFileSync(path.join(frontendDir, "contract-info.json"), jsonContent, "utf8");

  console.log("Updated frontend/contract-data.js and frontend/contract-info.json with deployment address and ABI.");
  console.log("--------------------------------------------------");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Deployment failed:", error);
    process.exit(1);
  });
